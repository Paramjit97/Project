package dec1;

public class Vowel {
    public static void main(String[]args){
        char ch='j';
        if ((ch=='a')|| (ch=='e')|| (ch=='i') || (ch=='o' )|| (ch=='u')){
            System.out.println("Char is vowel");
        }
        else{
            System.out.println("Char is consonant");
        }
    }
}
